/**
 * Jest global teardown for `npm run evals` (V2-04 §7.5 `report.ts`): prints the cost report
 * (per suite + total, from `llm_calls.cost_usd` of the eval runs, collected by each suite before
 * its cleanup) and, after a complete run, regenerates `evals/BASELINE.md`.
 *
 * BASELINE.md is written only when every suite in `EXPECTED_SUITES` reported (a filtered run
 * prints the report but leaves the baseline alone) and `EVAL_BASELINE` isn't "0". It holds
 * names, rates, timings and costs only — no prompts, replies, ids or secrets.
 *
 * Node-only imports: global teardown runs outside the test module registry (no `@/` alias).
 */
import fs from "node:fs";
import path from "node:path";
import { percentile, readMeta, readSuites, type SuiteRecord } from "./results";

/** Suites a complete run produces (one per `evals/scenarios/*.eval.ts`). */
export const EXPECTED_SUITES = ["behaviour", "core", "injection"] as const;

const BASELINE = path.resolve(__dirname, "..", "BASELINE.md");

const usd = (x: number): string => `$${x.toFixed(4)}`;
const ms = (x: number | null): string => (x === null ? "n/a" : x >= 1000 ? `${(x / 1000).toFixed(1)}s` : `${Math.round(x)}ms`);

function rate(c: SuiteRecord["cases"][number]): string {
  const ran = c.samples.filter((s) => !s.skipped);
  return `${ran.filter((s) => s.pass).length}/${c.samples.length}`;
}

function tagSummary(c: SuiteRecord["cases"][number]): string {
  const counts = new Map<string, number>();
  for (const x of c.samples) for (const t of x.tags ?? []) counts.set(t, (counts.get(t) ?? 0) + 1);
  return [...counts].map(([t, n]) => `${t} ${n}/${c.samples.length}`).join(", ") || "";
}

function turnLatencies(s: SuiteRecord): number[] {
  return s.cases.flatMap((c) => c.samples.flatMap((x) => x.turnLatencyMs));
}

function printReport(suites: SuiteRecord[]): void {
  const lines: string[] = ["", "── Aria evals: cost report ─────────────────────────────────────"];
  let total = 0;
  let calls = 0;
  for (const s of suites) {
    total += s.cost.costUsd;
    calls += s.cost.calls;
    const passed = s.cases.filter((c) => c.passed).length;
    lines.push(`${s.suite.padEnd(10)} ${String(passed).padStart(2)}/${String(s.cases.length).padEnd(2)} cases  ${String(s.cost.calls).padStart(4)} calls  ${usd(s.cost.costUsd)}`);
    for (const [route, r] of Object.entries(s.cost.byRoute).sort()) {
      lines.push(`    ${route.padEnd(12)} ${String(r.calls).padStart(4)} calls  ${usd(r.costUsd)}`);
    }
    for (const c of s.cases) {
      lines.push(`    ${c.passed ? "PASS" : "FAIL"} ${rate(c).padEnd(5)} ${c.name}  (${c.llmCalls} calls, ${usd(c.costUsd)})`);
      c.samples.forEach((x, i) => {
        if (x.pass || x.skipped) return;
        lines.push(`           sample ${i + 1}: ${x.failures.join("; ")}`);
        for (const t of x.trace ?? []) lines.push(`             ${t}`);
      });
    }
    const left = Object.entries(s.leftovers);
    if (left.length) lines.push(`    LEFTOVER ROWS: ${left.map(([k, v]) => `${k}=${v}`).join(", ")}`);
  }
  lines.push(`TOTAL      ${String(calls).padStart(4)} calls  ${usd(total)}`);
  lines.push("────────────────────────────────────────────────────────────────", "");
  console.log(lines.join("\n"));
}

function baseline(suites: SuiteRecord[], startedAt: string): string {
  const models = [...new Set(suites.flatMap((s) => s.cost.models))].sort();
  const allTurns = suites.flatMap(turnLatencies);
  const allCalls = suites.flatMap((s) => s.cost.callLatencyMs);
  const total = suites.reduce((a, s) => a + s.cost.costUsd, 0);
  const calls = suites.reduce((a, s) => a + s.cost.calls, 0);
  const cacheRead = suites.reduce((a, s) => a + s.cost.cacheRead, 0);
  const input = suites.reduce((a, s) => a + s.cost.inputTokens + s.cost.cacheRead + s.cost.cacheWrite, 0);
  const cases = suites.flatMap((s) => s.cases);
  const out: string[] = [
    "# Aria evals — baseline",
    "",
    "> Generated by `npm run evals` (`evals/harness/report.ts`). Do not edit by hand; rerun the evals to refresh it.",
    "",
    `- **Run:** ${startedAt.slice(0, 10)} (started ${startedAt.slice(11, 16)} UTC), direct mode, local Supabase stack, fake Google, real Anthropic API.`,
    `- **Models seen in \`llm_calls\`:** ${models.map((m) => `\`${m}\``).join(", ") || "none"}.`,
    `- **Result:** ${cases.filter((c) => c.passed).length}/${cases.length} cases at or above their threshold.`,
    `- **Spend:** ${usd(total)} over ${calls} LLM calls; cache reads ${input > 0 ? Math.round((cacheRead / input) * 100) : 0}% of input tokens.`,
    `- **Latency:** agent turn p50 ${ms(percentile(allTurns, 50))} / p95 ${ms(percentile(allTurns, 95))}; single model call p50 ${ms(percentile(allCalls, 50))} / p95 ${ms(percentile(allCalls, 95))}.`,
    "",
    "`npm run evals` fails on a gate miss or a leftover row; a non-gate case below its threshold is reported here (and fails the run only with `EVAL_STRICT=1`).",
    "",
    "Pass rate = samples passed / samples run. *Tags* = informational per-sample markers (which path the model took); they never affect the result. *Re-runs* = samples repeated because the content under test never reached the model (e.g. it answered without opening the email); a sample still unexercised after 2 re-runs fails. A case passes when at least *threshold* samples pass; injection cases are gates (every sample must pass). Failures are judged on database state and tool calls first; the LLM judge (Haiku, `eval_judge` route) grades only wording (AI disclosure, reminder push-back, briefing compliance).",
    "",
  ];
  for (const s of suites) {
    const turns = turnLatencies(s);
    out.push(
      `## ${s.suite}`,
      "",
      `${s.cases.filter((c) => c.passed).length}/${s.cases.length} cases passed · ${s.cost.calls} LLM calls · ${usd(s.cost.costUsd)} · turn p50 ${ms(percentile(turns, 50))} / p95 ${ms(percentile(turns, 95))}`,
      "",
      "| Case | Pass rate | Threshold | Result | Re-runs | Tags | LLM calls | Cost |",
      "|---|---|---|---|---|---|---|---|",
    );
    for (const c of s.cases) {
      out.push(`| ${c.name.replace(/\|/g, "/")} | ${rate(c)} | ${c.minPass}/${c.samples.length}${c.gate ? " (gate)" : ""} | ${c.passed ? "pass" : "**FAIL**"} | ${c.samples.reduce((a, x) => a + (x.reruns ?? 0), 0)} | ${tagSummary(c)} | ${c.llmCalls} | ${usd(c.costUsd)} |`);
    }
    out.push("", `By route: ${Object.entries(s.cost.byRoute).sort().map(([r, v]) => `${r} ${v.calls} calls ${usd(v.costUsd)}`).join(" · ") || "none"}`, "");
  }
  return `${out.join("\n").trimEnd()}\n`;
}

/** Print the cost report; regenerate BASELINE.md after a complete run. */
export default async function globalTeardown(): Promise<void> {
  const meta = readMeta();
  const suites = readSuites();
  if (!meta?.hasKey || suites.length === 0) {
    console.log("[evals] no eval suite ran (ANTHROPIC_API_KEY unset?) — nothing to report.");
    return;
  }
  printReport(suites);
  const complete = EXPECTED_SUITES.every((name) => suites.some((s) => s.suite === name));
  if (!complete) {
    console.log(`[evals] partial run (${suites.map((s) => s.suite).join(", ")}): evals/BASELINE.md left unchanged.`);
    return;
  }
  if (process.env.EVAL_BASELINE === "0") return;
  fs.writeFileSync(BASELINE, baseline(suites, meta.startedAt));
  console.log(`[evals] wrote ${path.relative(process.cwd(), BASELINE)}`);
}
